from pydantic import BaseModel, Field, EmailStr
from typing import Optional
from datetime import datetime

# --- VENDOR SCHEMAS ---
class VendorBase(BaseModel):
    name: str = Field(..., example="Gupta Sweets & Bakery")
    fssai_license: str = Field(..., example="11519024000111")
    shop_category: str = Field(..., example="Bakery")

class VendorCreate(VendorBase):
    longitude: float = Field(..., description="GPS Longitude", example=77.2090)
    latitude: float = Field(..., description="GPS Latitude", example=28.6139)

class VendorResponse(VendorBase):
    id: int
    rating: float
    is_suspended: bool
    latitude: Optional[float] = None
    longitude: Optional[float] = None

    class Config:
        from_attributes = True


# --- STUDENT SCHEMAS ---
class StudentBase(BaseModel):
    name: str = Field(..., example="Rahul Sharma")
    email: EmailStr = Field(..., example="rahul@college.edu")

class StudentCreate(StudentBase):
    pass

class StudentResponse(StudentBase):
    id: int

    class Config:
        from_attributes = True


# --- DEAL (MYSTERY BOX) SCHEMAS ---
class DealBase(BaseModel):
    title: Optional[str] = Field("Surplus Mystery Box", description="Appetizing title for the box")
    description: Optional[str] = Field(None, description="Customer-facing mystery description (contents secret)")
    dietary_tag: Optional[str] = Field("Vegetarian", description="Dietary preference tag")
    image_url: Optional[str] = Field(None, description="Mystery visual cover image")
    original_value: float = Field(..., gt=0, description="Actual value of the food")
    start_price: float = Field(..., gt=0, description="Price at listing")
    min_price: float = Field(..., gt=0, description="Absolute lowest price it can drop to")
    quantity: int = Field(..., gt=0, description="Number of boxes available")
    closing_time: datetime = Field(..., description="When the shop closes / food expires")

class DealCreate(DealBase):
    # vendor_id is optional and IGNORED: the listing shop is taken from the
    # signed vendor token on the request.
    vendor_id: Optional[int] = None

class DealResponse(DealBase):
    id: int
    created_at: datetime
    is_active: bool
    current_price: Optional[float] = Field(
        None, description="Live decayed price — render this, not start_price"
    )
    discount_percent: Optional[int] = None

    class Config:
        from_attributes = True

class DealWithVendorResponse(DealResponse):
    vendor: VendorResponse

    class Config:
        from_attributes = True

# --- RESERVATION SCHEMAS ---
class ReserveRequest(BaseModel):
    deal_id: int

class ReserveResponse(BaseModel):
    success: bool
    message: str
    reserved_price: Optional[float] = None
    expires_in_seconds: Optional[int] = None

# --- PICKUP & ACCOUNTABILITY SCHEMAS ---
class CompleteDealRequest(BaseModel):
    student_id: int = 1
    pickup_code: Optional[str] = None

class RateVendorRequest(BaseModel):
    rating: float = Field(..., ge=1.0, le=5.0, description="Rating from 1 to 5 stars")

# --- ORDER & PICKUP VERIFICATION SCHEMAS ---
class CreateOrderRequest(BaseModel):
    deal_id: int
    payment_method: str = "UPI"
    client_request_id: Optional[str] = Field(
        None,
        max_length=64,
        description="Idempotency key generated by the client so retries never double-charge",
    )

class OrderResponse(BaseModel):
    id: int
    deal_id: int
    student_id: int
    vendor_id: int
    pickup_code: str
    status: str
    paid_price: float
    original_value: float
    reserved_at: datetime
    collected_at: Optional[datetime] = None

    class Config:
        from_attributes = True

class VerifyPickupRequest(BaseModel):
    # NOTE: vendor_id is intentionally NOT accepted here. The redeeming store is
    # taken from the signed bearer token, so a client cannot verify another
    # store's codes.
    pickup_code: str

class VerifyPickupResponse(BaseModel):
    success: bool
    message: str
    order: Optional[dict] = None
